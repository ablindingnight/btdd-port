#!/usr/bin/env python3
"""Compile shaders/*.hlsl for btdd_play's GPU path and write src/platform/gpu_shaders.h.

  python tools/build_shaders.py [--fxc PATH]

Each *.vert.hlsl / *.frag.hlsl becomes DXBC shader model 5.1 (what SDL3's GPU API takes for D3D12) through fxc
from the Windows SDK, embedded as a byte array. The header is committed, so building the port does not need the
Windows SDK; run this after editing a shader. (Vulkan SPIR-V / Metal MSL are not generated yet: on those backends
btdd_play keeps its SDL_Renderer path.)
"""
import argparse
import glob
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, 'shaders')
OUT = os.path.join(REPO, 'src', 'platform', 'gpu_shaders.h')


def find_fxc():
    roots = glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe')
    return sorted(roots)[-1] if roots else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fxc', default=find_fxc())
    a = ap.parse_args()
    if not a.fxc or not os.path.isfile(a.fxc):
        print('fxc.exe not found (Windows SDK); pass --fxc')
        return 2
    tmp = os.path.join(REPO, 'build', 'shaders')
    os.makedirs(tmp, exist_ok=True)
    entries = []
    out = ['/* Generated by tools/build_shaders.py from shaders/*.hlsl (our own shaders, MIT). Do not edit. */',
           '#ifndef BTDD_GPU_SHADERS_H', '#define BTDD_GPU_SHADERS_H', '#include <stddef.h>', '#include <stdint.h>', '']
    for path in sorted(glob.glob(os.path.join(SRC, '*.hlsl'))):
        base = os.path.basename(path)[:-5]  # e.g. crt.frag
        name, stage = base.rsplit('.', 1)
        profile = 'vs_5_1' if stage == 'vert' else 'ps_5_1'
        obj = os.path.join(tmp, base + '.dxbc')
        r = subprocess.run([a.fxc, '/nologo', '/O3', '/T', profile, '/E', 'main', '/Fo', obj, path],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stdout + r.stderr)
            return 1
        data = open(obj, 'rb').read()
        ident = 'shader_%s_%s' % (name, stage)
        out.append('static const uint8_t %s[%d] = {' % (ident, len(data)))
        for i in range(0, len(data), 20):
            out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 20]) + ',')
        out.append('};')
        entries.append((name, stage, ident, len(data)))
        print('%-24s %5d bytes' % (base, len(data)))
    out += ['', 'typedef struct GpuShaderBlob {', '    const char *name;', '    int fragment;',
            '    const uint8_t *code;', '    size_t size;', '} GpuShaderBlob;', '',
            'static const GpuShaderBlob gpu_shader_blobs[] = {']
    for name, stage, ident, n in entries:
        out.append('    {"%s", %d, %s, sizeof %s},' % (name, 1 if stage == 'frag' else 0, ident, ident))
    out += ['};', '#define GPU_SHADER_BLOB_COUNT (int)(sizeof gpu_shader_blobs / sizeof gpu_shader_blobs[0])', '',
            '#endif', '']
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
